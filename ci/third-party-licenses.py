#!/usr/bin/env python3
"""Generate THIRD-PARTY-LICENSES.txt: the licenses of every Rust crate that ends up in a Horcrux build.

    python3 ci/third-party-licenses.py            # (re)write THIRD-PARTY-LICENSES.txt
    python3 ci/third-party-licenses.py --check    # exit 1 if the committed file is stale
    python3 ci/third-party-licenses.py --out FILE # write somewhere else (release assets)

Input is `cargo metadata --locked` (needs cargo and the crate sources in the cargo registry; it
never builds anything). The dependency graph is walked from the workspace members along normal and
build dependencies only, for every target platform, so test-only crates are not listed and the
result is a superset of what any one binary links. Output is deterministic for a given Cargo.lock:
no dates, sorted, license texts de-duplicated, so `--check` can compare bytes.

Crates that ship no license file are listed with their declared SPDX expression and a pointer to
the SPDX text instead of an invented text.
"""
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(ROOT, "THIRD-PARTY-LICENSES.txt")
LICENSE_FILE_RE = re.compile(r"^(licen[cs]e|copying|unlicense|notice)([-_.].*)?$", re.I)


def metadata():
    out = subprocess.check_output(
        ["cargo", "metadata", "--locked", "--format-version", "1"], cwd=ROOT, text=True
    )
    return json.loads(out)


def runtime_closure(md):
    """Package ids reachable from the workspace members through normal/build dependencies."""
    nodes = {n["id"]: n for n in md["resolve"]["nodes"]}
    seen, todo = set(), list(md["workspace_members"])
    while todo:
        pid = todo.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k.get("kind") in (None, "build") for k in dep["dep_kinds"]):
                todo.append(dep["pkg"])
    return seen


def license_files(pkg):
    d = os.path.dirname(pkg["manifest_path"])
    found = []
    for dp, dns, fns in os.walk(d):
        # only the crate's own top level and a license/ directory, not vendored sub-projects
        rel = os.path.relpath(dp, d)
        if rel != "." and not re.match(r"^licen[cs]es?$", rel, re.I):
            dns[:] = []
            continue
        for fn in sorted(fns):
            if LICENSE_FILE_RE.match(fn):
                try:
                    with open(os.path.join(dp, fn), encoding="utf-8") as f:
                        found.append((fn, f.read().strip().replace("\r\n", "\n")))
                except (UnicodeDecodeError, OSError):
                    pass
    return found


def build():
    md = metadata()
    keep = runtime_closure(md)
    members = set(md["workspace_members"])
    pkgs = sorted(
        (p for p in md["packages"] if p["id"] in keep and p["id"] not in members),
        key=lambda p: (p["name"], p["version"]),
    )
    texts = {}  # sha -> (text, [crate labels])
    no_text, rows = [], []
    for p in pkgs:
        label = f'{p["name"]} {p["version"]}'
        expr = p.get("license") or ("see " + p["license_file"] if p.get("license_file") else "UNKNOWN")
        rows.append((label, expr, p.get("repository") or p.get("homepage") or ""))
        files = license_files(p)
        if not files:
            no_text.append((label, expr))
        for _, text in files:
            h = hashlib.sha256(text.encode()).hexdigest()
            texts.setdefault(h, (text, []))[1].append(label)
    ws = sorted({p["name"] for p in md["packages"] if p["id"] in members})
    ws_license = sorted({p.get("license") or "GPL-3.0" for p in md["packages"] if p["id"] in members})

    o = []
    w = o.append
    w("Horcrux: third-party licenses")
    w("=" * 29)
    w("")
    w(f"Horcrux itself is free software under {', '.join(ws_license)} (see LICENSE).")
    w(f"It is built from {len(pkgs)} third-party Rust crates, listed below with their license and")
    w("followed by the license texts. Generated by ci/third-party-licenses.py from Cargo.lock; do")
    w("not edit by hand. The list covers every crate that can be compiled into a Horcrux binary on")
    w("any supported platform (normal and build dependencies, no test-only crates). Operating system")
    w("packages on a Horcrux install (Gentoo ebuilds) carry their own licenses, recorded by Portage")
    w("(`equery meta <package>`).")
    w("")
    w("External programs Horcrux runs as separate processes (never linked, no code copied):")
    w("QEMU (GPL-2.0; the Horcrux Console reads guest screens through QEMU's D-Bus display")
    w("interface) and FFmpeg (LGPL-2.1+ or GPL-2.0+ depending on the distribution's build; the")
    w("Horcrux Console encoder runs `ffmpeg` as a child process). Both come from the OS packages.")
    w("")
    w("System libraries loaded at run time when present (dlopen, no build-time headers, no code")
    w("copied, used unmodified from the OS packages): libx264 (GPL-2.0+; the console's in-process")
    w("H.264 encoder) and FFmpeg's libavcodec/libavutil (LGPL-2.1+ or GPL-2.0+; H.264 decoding in")
    w("the Horcrux Console desktop client).")
    w("")
    w("Horcrux workspace crates (not listed below): " + ", ".join(ws))
    w("")
    w("-" * 78)
    w(f"1. Crates ({len(pkgs)})")
    w("-" * 78)
    w("")
    for label, expr, repo in rows:
        w(f"{label}")
        w(f"    license: {expr}")
        if repo:
            w(f"    source:  {repo}")
    w("")
    w("-" * 78)
    w(f"2. License texts ({len(texts)} distinct)")
    w("-" * 78)
    for i, (h, (text, who)) in enumerate(sorted(texts.items(), key=lambda kv: (kv[1][1][0], kv[0])), 1):
        w("")
        w(f"[{i}] used by: " + ", ".join(sorted(set(who))))
        w("")
        w(text)
        w("")
        w("~" * 78)
    if no_text:
        w("")
        w("-" * 78)
        w("3. Crates that ship no license file")
        w("-" * 78)
        w("")
        w("These crates declare their license in Cargo.toml but include no license text in the")
        w("published package. The standard text of each SPDX identifier is at")
        w("https://spdx.org/licenses/<identifier>.html.")
        w("")
        for label, expr in no_text:
            w(f"{label}: {expr}")
    return "\n".join(o) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", default=DEFAULT_OUT)
    a = ap.parse_args()
    text = build()
    if a.check:
        try:
            cur = open(DEFAULT_OUT, encoding="utf-8").read()
        except OSError:
            cur = ""
        if cur != text:
            print("THIRD-PARTY-LICENSES.txt is stale: run python3 ci/third-party-licenses.py and commit it", file=sys.stderr)
            return 1
        print("THIRD-PARTY-LICENSES.txt is up to date")
        return 0
    with open(a.out, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {a.out} ({len(text) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
