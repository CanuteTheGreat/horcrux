#!/usr/bin/env python3
"""Generate .forgejo/workflows/live-iso-<edition>-systemd-<arch>.yml from its OpenRC twin (init-parity phase 3).

The systemd twin builds the same edition/arch with INIT=systemd. Trigger differs on purpose: the OpenRC daily builds on every image-input push to
main; the systemd daily runs on a fixed nightly slot (staggered per image, never the same hour as another systemd image on that runner class) plus
workflow_dispatch and v* tags, and skips itself when the published systemd daily is already from the current main commit. That keeps the scarce
KVM runners from building two ISOs of the same edition for every push. Usage: gen-systemd-workflows.py [--check]   (CI runs --check)
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WF = os.path.join(HERE, "..", ".forgejo", "workflows")
COMMON = "build/live-iso/common"
# image id -> nightly UTC slot (minute hour). 09:17/11:17 UTC = 01:17/03:17 PST on the kvm-x86_64 runners; arm64 has its own runners.
SLOTS = {
    "server-openrc-x86_64": "17 9 * * *",
    "gnome-light-openrc-x86_64": "17 11 * * *",
    "server-openrc-aarch64": "47 9 * * *",
}


def render(src_text, img):
    sd = img.replace("-openrc-", "-systemd-")
    t = src_text.replace(img, sd)
    t = t.replace("horcrux-server-openrc-daily", "horcrux-server-systemd-daily").replace("-openrc-daily-", "-systemd-daily-")
    # trigger block: everything from `on:` up to the concurrency comment/block
    m = re.search(r"(?ms)^on:\n.*?(?=^(# Per variant|concurrency:))", t)
    if not m:
        raise SystemExit(f"{img}: no on: block")
    on = (
        "on:\n"
        "  # systemd twin (init-parity phase 3): a nightly slot staggered against the other images, not every main push (one ISO at a time on the\n"
        "  # scarce KVM runners); skipped when the published systemd daily already is the current main commit. v* tags build the stable ISO.\n"
        "  schedule:\n"
        f"    - cron: '{SLOTS[img]}'\n"
        "  push:\n"
        "    tags: ['v*']\n"
        "  workflow_dispatch:\n"
        "    inputs:\n"
        "      mode:\n"
        "        description: 'daily (publish to the rolling pre-release) or dry (build + test only)'\n"
        "        required: false\n"
        "        default: 'dry'\n\n"
    )
    t = t[:m.start()] + on + t[m.end():]
    head = (f"# GENERATED by ci/gen-systemd-workflows.py from live-iso-{img}.yml (the OpenRC twin): edit that file or the generator, then re-run it.\n"
            f"# systemd variant of the same image: INIT=systemd (gentoo/stage3 *-systemd, ctg binhost systemd lane, live services as units).\n")
    t = head + t
    # INIT env next to ARCH
    t = re.sub(r"(?m)^(\s+)ARCH: (\S+)\n", lambda mm: f"{mm.group(1)}ARCH: {mm.group(2)}\n{mm.group(1)}INIT: systemd\n", t, count=1)
    # skip guard for the nightly
    guard = (
        "          # nightly: nothing new on main since the last PASSING systemd daily of this image -> do not occupy the runner\n"
        f"          if [ \"${{GITHUB_EVENT_NAME}}\" = schedule ] && sh {COMMON}/ci-already-published.sh {sd}; then exit 0; fi\n"
    )
    t = t.replace("          set -u\n", "          set -u\n" + guard, 1)
    return t


def main():
    check = "--check" in sys.argv
    bad = 0
    for img in SLOTS:
        src = os.path.join(WF, f"live-iso-{img}.yml")
        dst = os.path.join(WF, f"live-iso-{img.replace('-openrc-', '-systemd-')}.yml")
        out = render(open(src).read(), img)
        cur = open(dst).read() if os.path.exists(dst) else ""
        if check:
            if cur != out:
                print(f"STALE {dst}: run ci/gen-systemd-workflows.py")
                bad = 1
        elif cur != out:
            open(dst, "w").write(out)
            print(f"wrote {dst}")
    sys.exit(bad)


if __name__ == "__main__":
    main()
