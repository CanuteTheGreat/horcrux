#!/usr/bin/env python3
"""Make Portage's package database match an image that was deliberately slimmed (the ISO has to fit below 2 GiB).

Run as the LAST step of a variant's size strip, inside the rootfs build. For every installed package it drops the CONTENTS
entries of files that the strip removed on purpose and that match the reviewed ALLOW list below; it never touches an entry that is
missing for any other reason. This is what INSTALL_MASK would have produced, so on the installed system `qcheck`/the
`package-contents-complete` QEMU gate show zero missing files, and anything else that goes missing (the 2026-11-03 `tar --exclude=dev/*`
bug, a strip that eats /usr/src or a toolchain header) stays visible and fails the gate.

Every pattern here must match a deletion made in the Dockerfile strips (gnome-light / gringotts / setup-rootfs.sh). Adding a pattern is a review
decision: it means "a user of the installed system does not need this, and re-emerging the package brings it back".

usage: vdb-prune.py [--groups core,dev[,gringotts-fw]] [ROOT]   (default groups: core,dev)
"""
import glob
import os
import re
import sys

GROUPS = {
  "core": [
    r"^/usr/share/doc/",
    r"^/usr/share/gtk-doc/",
    r"^/usr/share/locale/",                      # non-English message catalogs
    r"^/usr/share/(gnome/)?help/",               # non-C help pages
    r"^/usr/share/ibus/dicts/",                  # non-English emoji dictionaries
    r"/__pycache__/[^/]*\.pyc$",                 # regenerated on first import
    r"^/(usr/)?lib/firmware/(qcom|netronome|mellanox|mrvl|qed|dpaa2|liquidio|cavium|cxgb4|bnx2x|bnx2)/",   # SoC / SmartNIC firmware
    r"^/usr/src/linux-[^/]+/arch/[^/]+/boot/(initrd|uki\.efi)$",   # sys-kernel/gentoo-kernel-bin's postinst builds these in the kernel tree and MOVES them to /boot
    r"^/usr/lib(64)?/gio/modules/giomodule\.cache$",              # regenerated by glib's postinst/triggers at the first boot
  ],
  # development leftovers of the desktop emerge (the toolchain's own headers/libs are KEPT by the strip, so they never match here)
  "dev": [
    r"^/usr/include/",
    r"^/usr/lib(64)?/.*\.a$",
    r"^/usr/lib/llvm/[^/]+/(include|bin)/",
    r"^/usr/lib/clang/",
  ],
  # the private gringotts image also drops firmware of hardware that laptop does not have
  "gringotts-fw": [
    r"^/(usr/)?lib/firmware/(nvidia|amdgpu|radeon|mediatek|ath10k|ath11k|ath12k|rtw89|brcm|qca)/",
  ],
}


def entry_path(line):
    if line.startswith("obj "):
        return " ".join(line.rstrip("\n").split(" ")[1:-2])
    if line.startswith("sym "):
        return line[4:line.index(" -> ")]
    if line.startswith("dir "):
        return line[4:].rstrip("\n")
    return None


def main():
    args = sys.argv[1:]
    groups = ["core", "dev"]
    if args[:1] == ["--groups"]:
        groups, args = args[1].split(","), args[2:]
    allow = [re.compile(p) for g in groups for p in GROUPS[g]]
    root = args[0] if args else "/"
    dropped = 0
    pkgs = 0
    for cf in glob.glob(os.path.join(root, "var/db/pkg/*/*/CONTENTS")):
        keep, changed = [], False
        with open(cf, errors="surrogateescape") as f:
            for line in f:
                p = entry_path(line)
                if p and not os.path.lexists(os.path.join(root, p.lstrip("/"))) and any(a.search(p) for a in allow):
                    dropped += 1
                    changed = True
                    continue
                keep.append(line)
        if changed:
            pkgs += 1
            with open(cf + ".new", "w", errors="surrogateescape") as f:
                f.writelines(keep)
            os.replace(cf + ".new", cf)
    print(f"vdb-prune: dropped {dropped} CONTENTS entries of intentionally stripped files in {pkgs} packages")


if __name__ == "__main__":
    main()
