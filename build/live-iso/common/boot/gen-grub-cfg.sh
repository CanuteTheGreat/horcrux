#!/bin/bash
# gen-grub-cfg.sh <volid> <title> <project> <arch> [memtest=none|bios|efi|both] [accent=cyan]
# Prints the GRUB menu of the live/installer ISO (Debian/Kali style) on stdout.
#
# One text-mode menu for every console: GRUB mirrors it on the VGA/EFI console and on the serial port, so
# both show exactly the same thing. Every entry has a hotkey (press the digit), the "Serial console" submenu
# repeats the entries with the kernel console on the UART instead of the screen.
#
#   1 Graphical install (default)   <proj>.installer=gui      (falls back to the text installer until the GUI ships)
#   2 Install (text mode)           <proj>.installer=1
#   3 Advanced (expert) install     <proj>.installer=expert
#   4 Automated install             <proj>.autoinstall=1      (answer file; no file -> guided installer)
#   5 Rescue mode                   <proj>.rescue=1           (find installed systems, chroot, reset password ...)
#   6 Rescue (forensic, no-touch)   <proj>.rescue=forensic    (every disk read-only at the block layer)
#   7 Try it live                   <proj>.live=1             (full product from RAM, disks untouched)
#   8 Try it live + persistence     <proj>.live=1 <proj>.persist=1 (USB-stick persistence, optional LUKS)
#   9 Safe graphics (nomodeset)     nomodeset <proj>.installer=1
#   0 Memory test                   memtest86+ (x86 only; BIOS and UEFI builds)
set -euo pipefail
VOLID=${1:?volid}; TITLE=${2:?title}; PROJ=${3:?project}; ARCH=${4:-x86_64}; MEMTEST=${5:-none}; ACCENT=${6:-cyan}

# UART name + whether GRUB itself can mirror the menu on it: from common/arch/<arch>.env (SERIAL_DEV, GRUB_SERIAL), with fallbacks
case "$ARCH" in
  aarch64) UART=${SERIAL_DEV:-ttyAMA0}; GRUB_SERIAL=${GRUB_SERIAL:-0} ;;
  x86_64)  UART=${SERIAL_DEV:-ttyS0};   GRUB_SERIAL=${GRUB_SERIAL:-1} ;;
  *)       UART=${SERIAL_DEV:-ttyS0};   GRUB_SERIAL=${GRUB_SERIAL:-0} ;;
esac
CMD="root=live:LABEL=${VOLID} rd.live.image rd.live.overlay.overlayfs=1 rootfstype=auto ro quiet loglevel=3"
SERIAL_ARGS="console=tty0 console=${UART},115200n8"
FORENSIC_ARGS="rd.md=0 rd.lvm=0 rd.luks=0 rd.dm=0"

cat <<CFG
# generated by common/boot/gen-grub-cfg.sh - do not edit by hand
set timeout=6
set default=0
set timeout_style=menu
insmod all_video
terminal_input console
terminal_output console
set gfxout=console
set color_normal=white/black
set color_highlight=black/${ACCENT}
set menu_color_normal=white/black
set menu_color_highlight=black/${ACCENT}
CFG
# product splash (official logo): graphical menu on the screen when the splash + font are on the ISO (GFX_OK=1, set by
# assemble-iso.sh); the entries and hotkeys are the same text, the serial mirror below stays a plain text menu
if [ "${GFX_OK:-0}" = 1 ]; then
cat <<CFG
if loadfont /boot/grub/fonts/unicode.pf2; then
    insmod gfxterm
    insmod png
    set gfxmode=auto
    if terminal_output gfxterm; then
        insmod gfxterm_background
        if background_image /boot/grub/splash.png; then set gfxout=gfxterm; else terminal_output console; fi
    fi
fi
CFG
fi
if [ "$GRUB_SERIAL" = 1 ]; then
cat <<CFG
# mirror the menu on COM1 when a UART exists (serial consoles, QEMU tests)
if serial --unit=0 --speed=115200; then
    terminal_input console serial
    terminal_output \$gfxout serial
fi
CFG
fi
cat <<CFG
search --no-floppy --label --set=root ${VOLID}

CFG

# entry <indent> <hotkey> <title> <extra kernel args>
entry() {
  local ind=$1 key=$2 title=$3 args=$4
  cat <<CFG
${ind}menuentry "${TITLE} - ${title}" --hotkey=${key} {
${ind}    linux /boot/vmlinuz ${CMD} ${args}
${ind}    initrd /boot/initramfs.img
${ind}}
CFG
}

entries() {   # <indent> <console args>
  local i=$1 c=$2
  entry "$i" 1 "Graphical install"                       "$c ${PROJ}.installer=gui"
  entry "$i" 2 "Install (text mode)"                     "$c ${PROJ}.installer=1"
  entry "$i" 3 "Advanced (expert) install"               "$c ${PROJ}.installer=expert"
  entry "$i" 4 "Automated install (answer file, ERASES the target disk)" "$c ${PROJ}.autoinstall=1"
  entry "$i" 5 "Rescue mode"                             "$c ${PROJ}.rescue=1"
  entry "$i" 6 "Rescue (forensic, no-touch: all disks read-only)" "$c ${FORENSIC_ARGS} ${PROJ}.rescue=forensic"
  entry "$i" 7 "Try it live (no install, disks untouched)" "$c ${PROJ}.live=1"
  entry "$i" 8 "Try it live with persistence (USB stick, optional encryption)" "$c ${PROJ}.live=1 ${PROJ}.persist=1"
  entry "$i" 9 "Safe graphics (nomodeset)"               "$c nomodeset ${PROJ}.installer=1"
}

entries "" ""
if [ "$ARCH" = x86_64 ]; then
  case "$MEMTEST" in bios|both)
cat <<CFG
if [ "\$grub_platform" = pc ]; then
    menuentry "${TITLE} - Memory test (memtest86+)" --hotkey=0 {
        linux16 /boot/memtest/memtest.bin console=ttyS0,115200
    }
fi
CFG
  ;; esac
  case "$MEMTEST" in efi|both)
cat <<CFG
if [ "\$grub_platform" = efi ]; then
    menuentry "${TITLE} - Memory test (memtest86+)" --hotkey=0 {
        chainloader /boot/memtest/memtest.efi
    }
fi
CFG
  ;; esac
fi
cat <<CFG

submenu "${TITLE} - Serial console (${UART} 115200)" --hotkey=s {
CFG
entries "    " "$SERIAL_ARGS"
echo "}"
