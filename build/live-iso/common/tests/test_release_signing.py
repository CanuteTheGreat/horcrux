def mkvdb(root, entries):
    for cat, pf, pn, pvr, lic, use, iuse, repo in entries:
        d = os.path.join(root, "var", "db", "pkg", cat, pf)
        os.makedirs(d)
        for k, v in (("PN", pn), ("PVR", pvr), ("LICENSE", lic), ("USE", use), ("IUSE", iuse), ("repository", repo), ("SLOT", "0")):
            open(os.path.join(d, k), "w").write(v + "\n")


class Sbom(unittest.TestCase):
    def setUp(self):
        self.t = tempfile.mkdtemp()
        mkvdb(self.t, [
            ("sys-libs", "zlib-1.3.1-r1", "zlib", "1.3.1-r1", "ZLIB", "amd64 elibc_glibc minizip static-libs", "minizip static-libs", "gentoo"),
            ("app-emulation", "horcrux-bin-0.1.0_p1", "horcrux-bin", "0.1.0_p1", "MIT", "amd64", "", "horcrux"),
        ])

    def tearDown(self):
        shutil.rmtree(self.t)

    def test_portage_components(self):
        c = {x["name"]: x for x in sbom.portage_components(self.t)}
        self.assertEqual(set(c), {"zlib", "horcrux-bin"})
        z = c["zlib"]
        self.assertEqual((z["group"], z["version"], z["type"]), ("sys-libs", "1.3.1-r1", "library"))
        props = {p["name"]: p["value"] for p in z["properties"]}
        self.assertEqual(props["gentoo:use"], "minizip static-libs")   # profile flags (amd64, elibc_*) dropped
        self.assertEqual(z["licenses"], [{"license": {"name": "ZLIB"}}])
        self.assertEqual(c["horcrux-bin"]["type"], "application")      # the product's own overlay package

    def test_cargo_lock_and_licenses(self):
        meta = {"packages": [{"name": "anyhow", "version": "1.0.98", "license": "MIT OR Apache-2.0", "id": "a"},
                             {"name": "horcrux-api", "version": "0.1.0", "license": "MIT", "id": "h"},
                             {"name": "gitdep", "version": "0.2.0", "license": "MIT/Apache-2.0", "id": "g"}],
                "workspace_members": ["h"]}
        c = {x["name"]: x for x in sbom.cargo_components(LOCK, meta)}
        self.assertEqual(c["anyhow"]["purl"], "pkg:cargo/anyhow@1.0.98")
        self.assertEqual(c["anyhow"]["hashes"][0]["content"][:8], "e16d2d33")
        self.assertEqual(c["anyhow"]["licenses"], [{"expression": "MIT OR Apache-2.0"}])
        self.assertEqual(c["gitdep"]["licenses"], [{"expression": "MIT OR Apache-2.0"}])
        self.assertIn("repository_url=https://example.invalid/x.git", c["gitdep"]["purl"])
        self.assertEqual(c["horcrux-api"]["type"], "application")
        self.assertNotIn("licenses", sbom.cargo_components(LOCK)[0])     # no metadata: no invented licenses

    def test_cli_writes_cyclonedx(self):
        lock = os.path.join(self.t, "Cargo.lock"); open(lock, "w").write(LOCK)
        out = os.path.join(self.t, "x.cdx.json")
        rc = sbom.main(["--root", self.t, "--cargo-lock", lock, "--name", "horcrux-server-openrc-daily-x86_64",
                        "--version", "abc", "--iso-sha256", "0" * 64, "-o", out])
        self.assertEqual(rc, 0)
        b = json.load(open(out))
        self.assertEqual((b["bomFormat"], b["specVersion"]), ("CycloneDX", "1.5"))
        self.assertEqual(b["metadata"]["component"]["type"], "operating-system")
        self.assertEqual(len(b["components"]), 5)
        refs = [x["bom-ref"] for x in b["components"]]
        self.assertEqual(len(refs), len(set(refs)))
        self.assertEqual(set(b["dependencies"][0]["dependsOn"]), set(refs))

    def test_refuses_without_os_packages(self):
        out = os.path.join(self.t, "y.cdx.json"); empty = os.path.join(self.t, "empty"); os.makedirs(empty)
        self.assertEqual(sbom.main(["--root", empty, "--name", "n", "--version", "v", "-o", out]), 1)
        self.assertFalse(os.path.exists(out))


@unittest.skipUnless(HAVE_GPG, "gpg/gpgv not installed")
class Signing(unittest.TestCase):
    def setUp(self):
        self.t = tempfile.mkdtemp()
        self.keys = {}
        for n in ("rel", "other"):
            g = os.path.join(self.t, "gh-" + n); os.makedirs(g, mode=0o700)
            subprocess.run(["gpg", "--homedir", g, "--batch", "--pinentry-mode", "loopback", "--passphrase", "",
                            "--quick-gen-key", f"Test {n} <{n}@example.invalid>", "ed25519", "sign", "1d"],
                           check=True, capture_output=True)
            sec = subprocess.run(["gpg", "--homedir", g, "--batch", "--armor", "--export-secret-keys"], check=True, capture_output=True, text=True).stdout
            pub = subprocess.run(["gpg", "--homedir", g, "--batch", "--armor", "--export"], check=True, capture_output=True, text=True).stdout
            pp = os.path.join(self.t, n + ".pub.asc"); open(pp, "w").write(pub)
            self.keys[n] = (sec, pp)
            subprocess.run(["gpgconf", "--homedir", g, "--kill", "all"], capture_output=True)
        self.f = os.path.join(self.t, "img.iso"); open(self.f, "wb").write(b"\x00" * 4096)

    def tearDown(self):
        shutil.rmtree(self.t, ignore_errors=True)

    def sign(self, key, *files, pub="rel"):
        env = dict(os.environ, RELEASE_PUBKEY=self.keys[pub][1], TMPDIR=self.t)
        env.pop("RELEASE_SIGNING_KEY", None)
        if key:
            env["RELEASE_SIGNING_KEY"] = self.keys[key][0]
        return subprocess.run(["bash", os.path.join(C, "sign-artifacts.sh"), *files], env=env, capture_output=True, text=True)

    def verify(self, *files, pub="rel"):
        return subprocess.run(["bash", os.path.join(C, "verify-artifacts.sh"), self.keys[pub][1], *files], capture_output=True, text=True,
                              env=dict(os.environ, TMPDIR=self.t))

    def test_sign_and_verify(self):
        r = self.sign("rel", self.f)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertTrue(open(self.f + ".asc").read().startswith("-----BEGIN PGP SIGNATURE-----"))
        self.assertEqual(self.verify(self.f).returncode, 0)

    def test_tampered_file_fails(self):
        self.assertEqual(self.sign("rel", self.f).returncode, 0)
        open(self.f, "ab").write(b"x")
        r = self.verify(self.f)
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("BAD", r.stderr)

    def test_foreign_key_refused(self):
        r = self.sign("other", self.f)        # signing key is not the committed one
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("not the committed release key", r.stderr)
        self.assertFalse(os.path.exists(self.f + ".asc"))
        self.assertEqual(self.sign("other", self.f, pub="other").returncode, 0)   # signed by another key ...
        self.assertNotEqual(self.verify(self.f, pub="rel").returncode, 0)          # ... never verifies as a release

    def test_no_key_refused(self):
        r = self.sign(None, self.f)
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("RELEASE_SIGNING_KEY is not set", r.stderr)

    def test_missing_signature(self):
        self.assertNotEqual(self.verify(self.f).returncode, 0)

    def test_publish_refuses_unsigned_before_any_upload(self):
        """publish-github.sh daily without the signing key: exit 1 and curl is never called (nothing reached GitHub)."""
        fake = os.path.join(self.t, "bin"); os.makedirs(fake)
        log = os.path.join(self.t, "curl.log")
        open(os.path.join(fake, "curl"), "w").write(f"#!/bin/sh\necho \"$@\" >> {log}\nexit 0\n"); os.chmod(os.path.join(fake, "curl"), 0o755)
        open(self.f + ".sha256", "w").write("0" * 64 + "  img.iso\n")
        sb = os.path.join(self.t, "s.cdx.json"); open(sb, "w").write("{}")
        status = os.path.join(self.t, "status.json"); open(status, "w").write("{}")
        for key, want in ((None, 1), ("other", 1)):
            env = {"PATH": fake + ":" + os.environ["PATH"], "GH_RELEASE_TOKEN": "x", "GITHUB_SHA": "a" * 40, "ARCH": "x86_64",
                   "SBOM": sb, "RELEASE_PUBKEY": self.keys["rel"][1], "TMPDIR": self.t, "HOME": self.t}
            if key:
                env["RELEASE_SIGNING_KEY"] = self.keys[key][0]
            r = subprocess.run(["bash", os.path.join(C, "publish-github.sh"), "daily", "horcrux", self.f, "", status],
                               env=env, capture_output=True, text=True)
            self.assertEqual(r.returncode, want, r.stdout + r.stderr)
            self.assertFalse(os.path.exists(log), "publish-github.sh talked to GitHub without a valid signature")

    def test_publish_refuses_without_sbom(self):
        open(self.f + ".sha256", "w").write("0" * 64 + "  img.iso\n")
        env = dict(os.environ, GH_RELEASE_TOKEN="x", GITHUB_SHA="a" * 40, ARCH="x86_64", SBOM="", RELEASE_SIGNING_KEY=self.keys["rel"][0],
                   RELEASE_PUBKEY=self.keys["rel"][1], TMPDIR=self.t, PATH="/nonexistent-curl:" + os.environ["PATH"])
        r = subprocess.run(["bash", os.path.join(C, "publish-github.sh"), "daily", "horcrux", self.f, "", ""], env=env, capture_output=True, text=True)
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("no SBOM", r.stdout + r.stderr)


class Wiring(unittest.TestCase):
    def test_committed_public_key(self):
        k = open(os.path.join(REPO, "keys", "release-signing.asc")).read()
        self.assertTrue(k.startswith("-----BEGIN PGP PUBLIC KEY BLOCK-----"))
        self.assertNotIn("PRIVATE KEY", k)

    def test_ci_run_never_publishes_unsigned(self):
        s = open(os.path.join(C, "ci-run.sh")).read()
        self.assertIn('fail publish "RELEASE_SIGNING_KEY is not set', s)
        self.assertIn("SBOM=$SBOM_FILE bash \"$HERE/publish-github.sh\"", s)
        self.assertIn('fail sbom "SBOM generation failed', s)

    def test_every_live_iso_workflow_passes_the_key(self):
        wf = os.path.join(REPO, ".forgejo", "workflows")
        names = [f for f in os.listdir(wf) if f.startswith("live-iso-") and f.endswith(".yml")]
        self.assertTrue(names)
        for f in names:
            self.assertIn("RELEASE_SIGNING_KEY: ${{ secrets.RELEASE_SIGNING_KEY }}", open(os.path.join(wf, f)).read(), f)


if __name__ == "__main__":
    unittest.main()
