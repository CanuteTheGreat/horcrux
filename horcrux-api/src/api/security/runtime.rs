//! Container runtime threat detection with Falco (Apache-2.0), optional and
//! off by default (`security.runtime.enabled`).
//!
//! Horcrux supervises one `falco` process with the modern eBPF probe (no
//! kernel module) and a curated rule set (`runtime-rules.yaml`: interactive
//! shell in a container, writes below /etc, privileged container start,
//! crypto-miner patterns). The process runs at low CPU priority inside a
//! cgroup v2 group with CPU and memory limits. Its JSON output is parsed into
//! events kept under `<data_dir>/security/runtime/` and sent through the
//! notification system as source `security`.
//!
//! Spike numbers that set the defaults are in docs/design/security-suite.md.
use super::{load_settings, notify};
use crate::AppState;
use horcrux_common::security::{
    runtime_priority_rank, RuntimeEvent, RuntimeSettings, RuntimeStatus, RUNTIME_PRIORITIES,
};
use serde_json::Value;
use std::collections::{HashMap, VecDeque};
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex, OnceLock};
use std::time::Duration;
use tokio::io::{AsyncBufReadExt, BufReader};

/// The curated Horcrux rules (product content, rewritten at every start).
pub const CURATED_RULES: &str = include_str!("runtime-rules.yaml");

fn dir() -> PathBuf {
    super::super::system_admin::data_dir()
        .join("security")
        .join("runtime")
}

/// Names of the curated rules.
pub fn curated_rule_names() -> Vec<String> {
    serde_yaml::from_str::<Vec<Value>>(CURATED_RULES)
        .unwrap_or_default()
        .iter()
        .filter_map(|r| r["rule"].as_str().map(String::from))
        .collect()
}

/// The falco.yaml Horcrux runs with. A generated file keeps the node's own
/// /etc/falco untouched and makes the behaviour independent of packaging.
pub fn falco_config(s: &RuntimeSettings, rules_file: &Path) -> String {
    let mut files = vec![rules_file.display().to_string()];
    files.extend(s.extra_rules_files.iter().cloned());
    let mut y = String::new();
    y.push_str("# Generated by Horcrux (security.runtime). Do not edit.\n");
    y.push_str("engine:\n  kind: modern_ebpf\n  modern_ebpf:\n    cpus_for_each_buffer: 2\n    buf_size_preset: 4\n    drop_failed_exit: false\n");
    y.push_str("rules_files:\n");
    for f in &files {
        y.push_str(&format!("  - \"{f}\"\n"));
    }
    if !s.disabled_rules.is_empty() {
        y.push_str("rules:\n");
        for r in &s.disabled_rules {
            y.push_str(&format!("  - disable:\n      rule: \"{r}\"\n"));
        }
    }
    y.push_str("load_plugins: [container]\nplugins:\n  - name: container\n");
    y.push_str(&format!(
        "    library_path: \"{}/libcontainer.so\"\n    init_config:\n      label_max_len: 100\n      with_size: false\n",
        s.plugin_dir.trim_end_matches('/')
    ));
    y.push_str("json_output: true\njson_include_output_property: true\njson_include_tags_property: false\ntime_format_iso_8601: true\npriority: debug\n");
    y.push_str("stdout_output:\n  enabled: true\nsyslog_output:\n  enabled: false\nfile_output:\n  enabled: false\nhttp_output:\n  enabled: false\nprogram_output:\n  enabled: false\n");
    y.push_str("webserver:\n  enabled: false\nwatch_config_files: false\nlog_stderr: true\nlog_syslog: false\nlog_level: info\n");
    y.push_str("metrics:\n  enabled: true\n  interval: 10s\n  output_rule: true\n  resource_utilization_enabled: true\n  kernel_event_counters_enabled: true\n  state_counters_enabled: false\n  rules_counters_enabled: false\n  libbpf_stats_enabled: false\n  convert_memory_to_mb: true\n  include_empty_values: false\n");
    y
}

/// What a restart is needed for (everything else applies live).
pub fn fingerprint(s: &RuntimeSettings) -> String {
    format!(
        "{}|{}|{:?}|{:?}|{}|{}|{}",
        s.falco_path,
        s.plugin_dir,
        s.extra_rules_files,
        s.disabled_rules,
        s.cpu_limit_percent,
        s.memory_limit_mb,
        s.nice
    )
}

/// One line of Falco's JSON output.
#[derive(Debug, PartialEq)]
pub enum Line {
    Event(RuntimeEvent),
    Metrics {
        events_per_sec: f64,
        drops: u64,
        cpu_percent: f64,
        memory_mb: f64,
    },
    Other,
}

fn field<'a>(f: &'a Value, k: &str) -> &'a str {
    f[k].as_str().unwrap_or("")
}

fn parse_time(v: &Value) -> i64 {
    v.as_str()
        .and_then(|t| chrono::DateTime::parse_from_rfc3339(t).ok())
        .map(|t| t.timestamp())
        .unwrap_or_else(|| chrono::Utc::now().timestamp())
}

/// Parse one stdout line of `falco -o json_output=true`.
pub fn parse_line(line: &str) -> Line {
    let Ok(v) = serde_json::from_str::<Value>(line) else {
        return Line::Other;
    };
    let rule = v["rule"].as_str().unwrap_or("");
    let f = &v["output_fields"];
    if rule == "Falco internal: metrics snapshot" {
        let n = |k: &str| f[k].as_f64().unwrap_or(0.0);
        return Line::Metrics {
            events_per_sec: n("scap.evts_rate_sec"),
            drops: f["scap.n_drops"].as_u64().unwrap_or(0),
            cpu_percent: n("falco.cpu_usage_perc"),
            memory_mb: n("falco.memory_rss_mb"),
        };
    }
    if rule.is_empty() || v["source"].as_str() == Some("internal") {
        return Line::Other;
    }
    let prio = match runtime_priority_rank(v["priority"].as_str().unwrap_or("")) {
        3 => RUNTIME_PRIORITIES[3],
        2 => RUNTIME_PRIORITIES[2],
        1 => RUNTIME_PRIORITIES[1],
        _ => RUNTIME_PRIORITIES[0],
    };
    let image = {
        let r = field(f, "container.image.repository");
        let t = field(f, "container.image.tag");
        if t.is_empty() {
            r.to_string()
        } else {
            format!("{r}:{t}")
        }
    };
    // The `output` text starts with "<time>: <Priority> "; keep the rest.
    let out = v["output"].as_str().unwrap_or("");
    let rest = out.split_once(": ").map(|x| x.1).unwrap_or(out);
    let message = match rest.split_once(' ') {
        Some((w, tail))
            if [
                "emergency",
                "alert",
                "critical",
                "error",
                "warning",
                "notice",
                "informational",
                "debug",
            ]
            .contains(&w.to_ascii_lowercase().as_str()) =>
        {
            tail.to_string()
        }
        _ => rest.to_string(),
    };
    Line::Event(RuntimeEvent {
        id: 0,
        time: parse_time(&v["time"]),
        rule: rule.to_string(),
        priority: prio.to_string(),
        container: field(f, "container.name").to_string(),
        image,
        process: field(f, "proc.name").to_string(),
        cmdline: field(f, "proc.cmdline").to_string(),
        user: field(f, "user.name").to_string(),
        message,
    })
}

/// Is this event kept under the settings?
pub fn keep(s: &RuntimeSettings, e: &RuntimeEvent) -> bool {
    runtime_priority_rank(&e.priority) >= runtime_priority_rank(&s.min_priority)
        && !s.ignore_containers.iter().any(|c| c == &e.container)
        && !s.disabled_rules.iter().any(|r| r == &e.rule)
}

// ------------------------------------------------------------- events

/// Newest events in memory and in `events.jsonl`.
pub struct EventStore {
    path: PathBuf,
    ring: VecDeque<RuntimeEvent>,
    next_id: u64,
    total: u64,
    lines_on_disk: usize,
}

impl EventStore {
    pub fn open(dir: &Path, keep: usize) -> Self {
        let path = dir.join("events.jsonl");
        let mut ring: VecDeque<RuntimeEvent> = VecDeque::new();
        let mut lines = 0;
        if let Ok(text) = std::fs::read_to_string(&path) {
            for l in text.lines() {
                lines += 1;
                if let Ok(e) = serde_json::from_str::<RuntimeEvent>(l) {
                    ring.push_back(e);
                    if ring.len() > keep {
                        ring.pop_front();
                    }
                }
            }
        }
        let next_id = ring.back().map(|e| e.id + 1).unwrap_or(1);
        let total = ring.len() as u64;
        Self {
            path,
            ring,
            next_id,
            total,
            lines_on_disk: lines,
        }
    }

    pub fn push(&mut self, mut e: RuntimeEvent, keep: usize) -> RuntimeEvent {
        e.id = self.next_id;
        self.next_id += 1;
        self.total += 1;
        if let Some(p) = self.path.parent() {
            let _ = std::fs::create_dir_all(p);
        }
        if let Ok(line) = serde_json::to_string(&e) {
            use std::io::Write;
            if let Ok(mut f) = std::fs::OpenOptions::new()
                .create(true)
                .append(true)
                .open(&self.path)
            {
                let _ = writeln!(f, "{line}");
                self.lines_on_disk += 1;
            }
        }
        self.ring.push_back(e.clone());
        while self.ring.len() > keep {
            self.ring.pop_front();
        }
        // Rewrite the file once it holds twice what is kept.
        if self.lines_on_disk > keep * 2 {
            let text: String = self
                .ring
                .iter()
                .filter_map(|x| serde_json::to_string(x).ok())
                .map(|l| l + "\n")
                .collect();
            let tmp = self.path.with_extension("jsonl.tmp");
            if std::fs::write(&tmp, text).is_ok() && std::fs::rename(&tmp, &self.path).is_ok() {
                self.lines_on_disk = self.ring.len();
            }
        }
        e
    }

    pub fn list(&self) -> Vec<RuntimeEvent> {
        self.ring.iter().rev().cloned().collect()
    }

    pub fn clear(&mut self) {
        self.ring.clear();
        self.lines_on_disk = 0;
        let _ = std::fs::remove_file(&self.path);
    }
}

fn store() -> &'static Mutex<Option<EventStore>> {
    static S: OnceLock<Mutex<Option<EventStore>>> = OnceLock::new();
    S.get_or_init(|| Mutex::new(None))
}

fn with_store<R>(keep: usize, f: impl FnOnce(&mut EventStore) -> R) -> R {
    let mut g = store().lock().unwrap_or_else(|e| e.into_inner());
    let s = g.get_or_insert_with(|| EventStore::open(&dir(), keep));
    f(s)
}

pub fn events(keep_n: usize) -> Vec<RuntimeEvent> {
    with_store(keep_n, |s| s.list())
}

pub fn clear_events(keep_n: usize) {
    with_store(keep_n, |s| s.clear())
}

pub fn events_since(keep_n: usize, since: i64) -> u32 {
    with_store(keep_n, |s| {
        s.ring.iter().filter(|e| e.time >= since).count() as u32
    })
}

// ------------------------------------------------------------- status

#[derive(Default)]
struct Live {
    running: bool,
    pid: Option<u32>,
    since: Option<i64>,
    restarts: u32,
    events_per_sec: f64,
    drops: u64,
    cpu: f64,
    mem: f64,
    limits_applied: bool,
    last_error: Option<String>,
    version: String,
}

fn live() -> &'static Mutex<Live> {
    static L: OnceLock<Mutex<Live>> = OnceLock::new();
    L.get_or_init(|| Mutex::new(Live::default()))
}

fn set_live(f: impl FnOnce(&mut Live)) {
    f(&mut live().lock().unwrap_or_else(|e| e.into_inner()));
}

pub fn is_running() -> bool {
    live().lock().map(|l| l.running).unwrap_or(false)
}

pub fn falco_bin(s: &RuntimeSettings) -> Option<PathBuf> {
    if s.falco_path.starts_with('/') {
        let p = PathBuf::from(&s.falco_path);
        p.is_file().then_some(p)
    } else {
        super::super::system_admin::which(&s.falco_path)
    }
}

pub async fn status(state: &AppState) -> RuntimeStatus {
    let s = load_settings(state).await.runtime;
    let bin = falco_bin(&s);
    let l = live().lock().unwrap_or_else(|e| e.into_inner());
    let (total, kept) = with_store(s.keep_events as usize, |st| {
        (st.total, st.ring.len() as u32)
    });
    RuntimeStatus {
        enabled: s.enabled,
        available: bin.is_some(),
        version: l.version.clone(),
        running: l.running,
        pid: l.pid,
        since: l.since,
        restarts: l.restarts,
        events_per_sec: l.events_per_sec,
        kernel_drops: l.drops,
        cpu_percent: l.cpu,
        memory_mb: l.mem,
        limits_applied: l.limits_applied,
        last_error: l.last_error.clone().or_else(|| {
            (s.enabled && bin.is_none()).then(|| format!("'{}' is not installed", s.falco_path))
        }),
        events_total: total,
        events_kept: kept,
        rules: curated_rule_names(),
    }
}

// ------------------------------------------------------------- cgroup

fn cgroup_root() -> PathBuf {
    PathBuf::from(std::env::var("HORCRUX_CGROUP_ROOT").unwrap_or_else(|_| "/sys/fs/cgroup".into()))
}

/// Create `horcrux-runtime-detection` with the limits; the path on success.
pub fn make_cgroup(s: &RuntimeSettings) -> Result<PathBuf, String> {
    let root = cgroup_root();
    if !root.join("cgroup.controllers").exists() {
        return Err("cgroup v2 is not mounted".into());
    }
    // Best effort: make cpu and memory available to children of the root.
    let _ = std::fs::write(root.join("cgroup.subtree_control"), "+cpu +memory");
    let p = root.join("horcrux-runtime-detection");
    std::fs::create_dir_all(&p).map_err(|e| format!("{}: {e}", p.display()))?;
    let quota = s.cpu_limit_percent as u64 * 1000;
    std::fs::write(p.join("cpu.max"), format!("{quota} 100000"))
        .map_err(|e| format!("cpu.max: {e}"))?;
    std::fs::write(
        p.join("memory.max"),
        (s.memory_limit_mb as u64 * 1024 * 1024).to_string(),
    )
    .map_err(|e| format!("memory.max: {e}"))?;
    let _ = std::fs::write(p.join("memory.swap.max"), "0");
    Ok(p)
}

/// Remove the group: rmdir works on a real cgroup; the fallback clears a
/// plain directory (tests with a fake cgroup root).
fn remove_cgroup(p: &Path) {
    if std::fs::remove_dir(p).is_err() {
        let _ = std::fs::remove_dir_all(p);
    }
}

fn join_cgroup(p: &Path, pid: u32) -> Result<(), String> {
    std::fs::write(p.join("cgroup.procs"), pid.to_string()).map_err(|e| e.to_string())
}

// ------------------------------------------------------------- supervisor

fn last_notified() -> &'static Mutex<HashMap<(String, String), i64>> {
    static L: OnceLock<Mutex<HashMap<(String, String), i64>>> = OnceLock::new();
    L.get_or_init(|| Mutex::new(HashMap::new()))
}

/// Whether this event may notify now (same rule + container at most once per
/// `notify_dedupe_secs`).
pub fn notify_due(s: &RuntimeSettings, e: &RuntimeEvent, now: i64) -> bool {
    if runtime_priority_rank(&e.priority) < runtime_priority_rank(&s.notify_min_priority) {
        return false;
    }
    let mut m = last_notified().lock().unwrap_or_else(|x| x.into_inner());
    let k = (e.rule.clone(), e.container.clone());
    if let Some(t) = m.get(&k) {
        if now - *t < s.notify_dedupe_secs as i64 {
            return false;
        }
    }
    m.insert(k, now);
    if m.len() > 4096 {
        m.retain(|_, t| now - *t < s.notify_dedupe_secs as i64);
    }
    true
}

async fn handle_line(state: &Arc<AppState>, line: &str) {
    match parse_line(line) {
        Line::Metrics {
            events_per_sec,
            drops,
            cpu_percent,
            memory_mb,
        } => set_live(|l| {
            l.events_per_sec = events_per_sec;
            l.drops = drops;
            l.cpu = cpu_percent;
            l.mem = memory_mb;
        }),
        Line::Event(e) => {
            let s = load_settings(state).await.runtime;
            if !keep(&s, &e) {
                return;
            }
            let e = with_store(s.keep_events as usize, |st| {
                st.push(e, s.keep_events as usize)
            });
            let now = chrono::Utc::now().timestamp();
            if notify_due(&s, &e, now) {
                let sev = if runtime_priority_rank(&e.priority) >= 3 {
                    "critical"
                } else {
                    "warning"
                };
                let who = if e.container.is_empty() {
                    "host"
                } else {
                    &e.container
                };
                notify(
                    state,
                    sev,
                    format!("{} ({who})", e.rule),
                    format!("{} Open Security > Runtime on this node.", e.message),
                )
                .await;
            }
        }
        Line::Other => {}
    }
}

async fn version_of(bin: &Path) -> String {
    let out = tokio::time::timeout(
        Duration::from_secs(10),
        tokio::process::Command::new(bin)
            .arg("--version")
            .stdin(std::process::Stdio::null())
            .kill_on_drop(true)
            .output(),
    )
    .await;
    match out {
        Ok(Ok(o)) => String::from_utf8_lossy(&o.stdout)
            .lines()
            .find_map(|l| {
                l.strip_prefix("Falco version:")
                    .map(|v| v.trim().to_string())
            })
            .unwrap_or_default(),
        _ => String::new(),
    }
}

struct Running {
    child: tokio::process::Child,
    fingerprint: String,
    cgroup: Option<PathBuf>,
    stderr_tail: Arc<Mutex<VecDeque<String>>>,
}

async fn start(state: &Arc<AppState>, s: &RuntimeSettings, bin: &Path) -> Result<Running, String> {
    let d = dir();
    std::fs::create_dir_all(&d).map_err(|e| format!("{}: {e}", d.display()))?;
    let rules = d.join("horcrux-rules.yaml");
    std::fs::write(&rules, CURATED_RULES).map_err(|e| e.to_string())?;
    let conf = d.join("falco.yaml");
    std::fs::write(&conf, falco_config(s, &rules)).map_err(|e| e.to_string())?;
    let mut cmd = tokio::process::Command::new(bin);
    cmd.arg("-c")
        .arg(&conf)
        .env("HOST_ROOT", "")
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .kill_on_drop(true);
    let nice = s.nice as i32;
    // SAFETY: only async-signal-safe libc calls between fork and exec.
    unsafe {
        cmd.pre_exec(move || {
            nix::libc::setpriority(nix::libc::PRIO_PROCESS, 0, nice);
            Ok(())
        });
    }
    let cg = make_cgroup(s);
    let mut child = cmd.spawn().map_err(|e| format!("{}: {e}", bin.display()))?;
    let pid = child.id();
    let mut limits = false;
    let mut cgroup = None;
    match (&cg, pid) {
        (Ok(p), Some(pid)) => match join_cgroup(p, pid) {
            Ok(()) => {
                limits = true;
                cgroup = Some(p.clone());
            }
            Err(e) => {
                tracing::warn!("security runtime: cgroup join failed: {e}");
                cgroup = Some(p.clone());
            }
        },
        (Err(e), _) => tracing::warn!("security runtime: no cgroup limits: {e}"),
        _ => {}
    }
    let stdout = child.stdout.take();
    let stderr = child.stderr.take();
    let st = state.clone();
    if let Some(o) = stdout {
        tokio::spawn(async move {
            let mut lines = BufReader::new(o).lines();
            while let Ok(Some(l)) = lines.next_line().await {
                handle_line(&st, &l).await;
            }
        });
    }
    let tail = Arc::new(Mutex::new(VecDeque::new()));
    if let Some(e) = stderr {
        let t = tail.clone();
        tokio::spawn(async move {
            let mut lines = BufReader::new(e).lines();
            while let Ok(Some(l)) = lines.next_line().await {
                let mut g = t.lock().unwrap_or_else(|x| x.into_inner());
                g.push_back(l);
                if g.len() > 12 {
                    g.pop_front();
                }
            }
        });
    }
    let version = version_of(bin).await;
    set_live(|l| {
        l.running = true;
        l.pid = pid;
        l.since = Some(chrono::Utc::now().timestamp());
        l.limits_applied = limits;
        l.version = version;
        l.last_error = match &cg {
            Err(e) => Some(format!("running without resource limits: {e}")),
            Ok(_) if !limits => Some("running without resource limits: cgroup join failed".into()),
            _ => None,
        };
    });
    Ok(Running {
        child,
        fingerprint: fingerprint(s),
        cgroup,
        stderr_tail: tail,
    })
}

async fn stop(mut r: Running) {
    let _ = r.child.start_kill();
    let _ = tokio::time::timeout(Duration::from_secs(15), r.child.wait()).await;
    if let Some(p) = r.cgroup {
        remove_cgroup(&p);
    }
    set_live(|l| {
        l.running = false;
        l.pid = None;
        l.events_per_sec = 0.0;
        l.cpu = 0.0;
        l.mem = 0.0;
    });
}

/// Start/stop/restart the detector to match the settings. Runs for the life
/// of the node; with `security.runtime.enabled` false it does nothing.
pub fn spawn_supervisor(state: Arc<AppState>) {
    tokio::spawn(async move {
        tokio::time::sleep(Duration::from_secs(5)).await;
        let mut running: Option<Running> = None;
        let mut hold_until: i64 = 0;
        loop {
            let s = load_settings(&state).await.runtime;
            let bin = falco_bin(&s);
            let now = chrono::Utc::now().timestamp();
            // Exited by itself?
            if let Some(r) = running.as_mut() {
                if let Ok(Some(status)) = r.child.try_wait() {
                    let tail: Vec<String> = r
                        .stderr_tail
                        .lock()
                        .map(|g| g.iter().cloned().collect())
                        .unwrap_or_default();
                    let msg = tail
                        .iter()
                        .rev()
                        .find(|l| l.to_ascii_lowercase().contains("error"))
                        .or(tail.last())
                        .cloned()
                        .unwrap_or_default();
                    set_live(|l| {
                        l.running = false;
                        l.pid = None;
                        l.restarts += 1;
                        l.last_error = Some(format!("falco exited ({status}): {msg}"));
                    });
                    if let Some(p) = r.cgroup.take() {
                        remove_cgroup(&p);
                    }
                    running = None;
                    hold_until = now + s.restart_delay_secs as i64;
                }
            }
            let want = s.enabled && bin.is_some();
            if let Some(r) = running.take() {
                if want && r.fingerprint == fingerprint(&s) {
                    running = Some(r);
                } else {
                    stop(r).await;
                }
            }
            if want && running.is_none() && now >= hold_until {
                if let Some(b) = &bin {
                    match start(&state, &s, b).await {
                        Ok(r) => running = Some(r),
                        Err(e) => {
                            set_live(|l| l.last_error = Some(e));
                            hold_until = now + s.restart_delay_secs as i64;
                        }
                    }
                }
            }
            if !want && running.is_none() {
                set_live(|l| {
                    if !s.enabled {
                        l.last_error = None;
                    }
                });
            }
            tokio::time::sleep(Duration::from_secs(3)).await;
        }
    });
}

