    #[test]
    fn falco_json_lines_become_events_and_metrics() {
        let l = r#"{"hostname":"h","output":"2026-11-27T12:08:50.7+0000: Error File below /etc opened for writing in container (file=/etc/x proc=sh) container_id=1","output_fields":{"container.name":"web","container.image.repository":"alpine","container.image.tag":"3.24","proc.name":"sh","proc.cmdline":"sh -c echo","user.name":"root"},"priority":"Error","rule":"HX write below /etc in container","source":"syscall","time":"2026-11-27T12:08:50.786359883Z"}"#;
        match parse_line(l) {
            Line::Event(e) => {
                assert_eq!(e.rule, "HX write below /etc in container");
                assert_eq!(e.priority, "error");
                assert_eq!(e.container, "web");
                assert_eq!(e.image, "alpine:3.24");
                assert_eq!(e.user, "root");
                assert!(
                    e.message.starts_with("File below /etc opened"),
                    "{}",
                    e.message
                );
                assert_eq!(e.time, 1795781330);
            }
            x => panic!("{x:?}"),
        }
        let m = r#"{"output":"Falco metrics snapshot","output_fields":{"falco.cpu_usage_perc":12.5,"falco.memory_rss_mb":133.3,"scap.evts_rate_sec":26423.9,"scap.n_drops":4},"priority":"Informational","rule":"Falco internal: metrics snapshot","source":"internal","time":"2026-11-27T12:08:54Z"}"#;
        assert_eq!(
            parse_line(m),
            Line::Metrics {
                events_per_sec: 26423.9,
                drops: 4,
                cpu_percent: 12.5,
                memory_mb: 133.3
            }
        );
        assert_eq!(parse_line("not json"), Line::Other);
        assert_eq!(
            parse_line("{\"rule\":\"x\",\"source\":\"internal\"}"),
            Line::Other
        );
    }

