    #[test]
    fn event_store_keeps_the_newest_and_survives_a_reopen() {
        let d = std::env::temp_dir().join(format!("hx-rt-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        let mut st = EventStore::open(&d, 3);
        for i in 0..8 {
            st.push(ev(&format!("r{i}"), "error", "c"), 3);
        }
        let l = st.list();
        assert_eq!(l.len(), 3);
        assert_eq!(l[0].rule, "r7");
        assert_eq!(l[0].id, 8);
        let st2 = EventStore::open(&d, 3);
        assert_eq!(st2.list().len(), 3);
        assert_eq!(st2.next_id, 9);
        let mut st2 = st2;
        st2.clear();
        assert!(st2.list().is_empty());
        let _ = std::fs::remove_dir_all(&d);
    }

