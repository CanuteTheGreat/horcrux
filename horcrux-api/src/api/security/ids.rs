//! Host intrusion detection (Linux audit) and file integrity (AIDE).
//!
//! * The audit rule set is product content, rendered from `audit` settings
//!   into `audit.rules_file` (a /etc/audit/rules.d drop-in that augenrules
//!   merges at boot on OpenRC and systemd alike) and loaded at once. Every
//!   rule carries a `hx-<kind>` key; turning audit off deletes exactly the
//!   rules with those keys and the file, nothing else.
//! * Events are collected with `ausearch --checkpoint ... --format raw` at
//!   low priority, parsed here, deduplicated against a stored watermark
//!   (ausearch repeats the checkpointed event) and kept as JSON lines in
//!   `<data_dir>/security/events.jsonl`, pruned to `events.keep`.
//! * The AIDE configuration is rendered from `integrity` settings into
//!   `<db_dir>/aide.conf` (JSON report on stdout); `init`, `check` and
//!   `accept` (`--update` + database rotation) run one at a time at low CPU
//!   and idle IO priority with a hard timeout.
//!
//! Every file path is read below `HORCRUX_SYSROOT` (tests use a fake root).
use super::super::system_admin::rooted;
use horcrux_common::security::{
    AuditSettings, EventSource, IntegritySettings, SecurityEvent, Severity,
};
use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::collections::BTreeMap;
use std::io::{BufRead, Write};
use std::path::{Path, PathBuf};

// ------------------------------------------------------------ audit rules

/// Built-in watches: path, permissions, kind.
pub const WATCHES: &[(&str, &str, &str)] = &[
    ("/etc/passwd", "wa", "identity"),
    ("/etc/shadow", "wa", "identity"),
    ("/etc/group", "wa", "identity"),
    ("/etc/gshadow", "wa", "identity"),
    ("/etc/sudoers", "wa", "identity"),
    ("/etc/sudoers.d", "wa", "identity"),
    ("/etc/doas.conf", "wa", "identity"),
    ("/etc/ssh/sshd_config", "wa", "sshd"),
    ("/etc/ssh/sshd_config.d", "wa", "sshd"),
    ("/etc/horcrux", "wa", "horcrux"),
    ("/usr/bin/horcrux-api", "wa", "binaries"),
    ("/usr/bin/horcrux", "wa", "binaries"),
    ("/usr/bin/horcrux-cli", "wa", "binaries"),
    ("/usr/bin/horcrux-guests", "wa", "binaries"),
    ("/usr/sbin/horcrux-api", "wa", "binaries"),
    ("/usr/libexec/horcrux", "wa", "binaries"),
    ("/usr/lib/horcrux", "wa", "binaries"),
    ("/usr/bin/su", "x", "sudo"),
    ("/bin/su", "x", "sudo"),
    ("/usr/bin/doas", "x", "sudo"),
];

/// Watches tied to `watch_modules` / `watch_time`.
const MODULE_WATCHES: &[&str] = &[
    "/usr/bin/kmod",
    "/bin/kmod",
    "/sbin/insmod",
    "/sbin/modprobe",
];
const TIME_WATCHES: &[&str] = &["/etc/localtime"];

/// Audit architectures for syscall rules on this build.
fn arches() -> &'static [&'static str] {
    if cfg!(target_arch = "x86_64") {
        &["b64", "b32"]
    } else {
        &["b64"]
    }
}

/// The rule file for `s`. `exists` decides which watch paths are present
/// (a watch on a missing parent directory makes auditctl refuse the file).
pub fn render_rules(s: &AuditSettings, exists: &dyn Fn(&str) -> bool) -> String {
    let mut o = String::new();
    o.push_str("## Horcrux host intrusion detection rule set (generated by horcrux-api from\n");
    o.push_str("## Security > Settings > Audit; changes here are overwritten). Every rule\n");
    o.push_str("## carries a hx-<kind> key; docs/SECURITY-SUITE.md lists them.\n");
    o.push_str(&format!("-b {}\n", s.backlog));
    let mut seen = std::collections::BTreeSet::new();
    let mut watch = |o: &mut String, p: &str, perm: &str, kind: &str| {
        if seen.insert(p.to_string()) && exists(p) {
            o.push_str(&format!("-w {p} -p {perm} -k hx-{kind}\n"));
        }
    };
    for (p, perm, kind) in WATCHES {
        // /bin/su and /usr/bin/su are often the same file (merged /usr):
        // one watch is enough and a duplicate rule is an auditctl error.
        if *p == "/bin/su" && exists("/usr/bin/su") {
            continue;
        }
        watch(&mut o, p, perm, kind);
    }
    if s.watch_modules {
        for a in arches() {
            o.push_str(&format!(
                "-a always,exit -F arch={a} -S init_module,finit_module,delete_module -k hx-modules\n"
            ));
        }
        for p in MODULE_WATCHES {
            if *p == "/bin/kmod" && exists("/usr/bin/kmod") {
                continue;
            }
            watch(&mut o, p, "x", "modules");
        }
    }
    if s.watch_time {
        for a in arches() {
            o.push_str(&format!(
                "-a always,exit -F arch={a} -S adjtimex,settimeofday,clock_settime -k hx-time\n"
            ));
        }
        for p in TIME_WATCHES {
            watch(&mut o, p, "wa", "time");
        }
    }
    for p in &s.extra_watch {
        watch(&mut o, p, "wa", "watch");
    }
    if s.immutable {
        o.push_str("-e 2\n");
    }
    o
}

/// Number of loaded rules with a Horcrux key in `auditctl -l` output.
pub fn count_loaded(auditctl_l: &str) -> u32 {
    auditctl_l
        .lines()
        .filter(|l| l.contains("key=hx-") || l.contains("-k hx-"))
        .count() as u32
}

/// `auditctl -s`: the rules are locked until reboot (`enabled 2`).
pub fn is_locked(auditctl_s: &str) -> bool {
    auditctl_s
        .lines()
        .any(|l| l.split_whitespace().collect::<Vec<_>>() == ["enabled", "2"])
}

// ------------------------------------------------------------ audit events

/// One raw audit record: type, time, serial and its fields.
#[derive(Debug, Clone, Default)]
pub struct Record {
    pub rtype: String,
    pub secs: i64,
    pub millis: u32,
    pub serial: u64,
    pub fields: BTreeMap<String, String>,
}

/// Parse `type=X msg=audit(1795700000.123:501): k=v k="v" msg='k=v ...'`.
pub fn parse_record(line: &str) -> Option<Record> {
    let line = line.trim();
    let rest = line.strip_prefix("type=")?;
    let (rtype, rest) = rest.split_once(' ')?;
    let rest = rest.trim_start().strip_prefix("msg=audit(")?;
    let (stamp, rest) = rest.split_once("):")?;
    let (time, serial) = stamp.split_once(':')?;
    let (secs, millis) = time.split_once('.').unwrap_or((time, "0"));
    let mut r = Record {
        rtype: rtype.to_string(),
        secs: secs.parse().ok()?,
        millis: millis.parse().unwrap_or(0),
        serial: serial.parse().ok()?,
        fields: BTreeMap::new(),
    };
    for tok in tokens(rest) {
        let tok = tok.strip_prefix("msg='").unwrap_or(&tok);
        let tok = tok.strip_suffix('\'').unwrap_or(tok);
        if let Some((k, v)) = tok.split_once('=') {
            let v = v.trim_matches('"');
            // Later duplicates (e.g. `uid` inside msg='') do not replace the
            // record's own field.
            r.fields
                .entry(k.to_string())
                .or_insert_with(|| v.to_string());
        }
    }
    Some(r)
}

/// Whitespace-separated tokens; double quotes keep spaces.
fn tokens(s: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let mut q = false;
    for c in s.chars() {
        match c {
            '"' => {
                q = !q;
                cur.push(c);
            }
            c if c.is_whitespace() && !q => {
                if !cur.is_empty() {
                    out.push(std::mem::take(&mut cur));
                }
            }
            c => cur.push(c),
        }
    }
    if !cur.is_empty() {
        out.push(cur);
    }
    out
}

/// Audit hex-encodes values with spaces or control characters (proctitle,
/// cmd, a multi-key `key`).
pub fn unhex(v: &str) -> String {
    if v.len() >= 2 && v.len().is_multiple_of(2) && v.chars().all(|c| c.is_ascii_hexdigit()) {
        let bytes: Option<Vec<u8>> = (0..v.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&v[i..i + 2], 16).ok())
            .collect();
        if let Some(b) = bytes {
            let s = String::from_utf8_lossy(&b).replace('\0', " ");
            if s.chars().all(|c| !c.is_control() || c == '\u{1}') {
                return s.trim().to_string();
            }
        }
    }
    v.to_string()
}

/// uid -> account name from `<sysroot>/etc/passwd`.
pub fn passwd_names() -> BTreeMap<String, String> {
    std::fs::read_to_string(rooted("/etc/passwd"))
        .unwrap_or_default()
        .lines()
        .filter_map(|l| {
            let f: Vec<&str> = l.split(':').collect();
            (f.len() > 2).then(|| (f[2].to_string(), f[0].to_string()))
        })
        .collect()
}

fn user_name(uid: &str, names: &BTreeMap<String, String>) -> String {
    match uid {
        "" => String::new(),
        "4294967295" | "-1" | "unset" => "unset".into(),
        u => names.get(u).cloned().unwrap_or_else(|| format!("uid {u}")),
    }
}

/// Record types turned into events without a rule key.
const USER_TYPES: &[&str] = &[
    "USER_LOGIN",
    "USER_AUTH",
    "USER_CMD",
    "ADD_USER",
    "DEL_USER",
    "ADD_GROUP",
    "DEL_GROUP",
    "USER_CHAUTHTOK",
    "USER_MGMT",
    "GRP_MGMT",
];

fn kind_severity(kind: &str, failed: bool) -> Severity {
    match kind {
        "identity" | "binaries" | "modules" => Severity::High,
        "sshd" | "horcrux" | "time" | "watch" => Severity::Medium,
        "auth" => Severity::Medium,
        "login" if failed => Severity::Medium,
        _ => Severity::Low,
    }
}

fn hx_keys(fields: &BTreeMap<String, String>) -> Vec<String> {
    let Some(k) = fields.get("key") else {
        return vec![];
    };
    unhex(k)
        .split('\u{1}')
        .filter_map(|k| k.strip_prefix("hx-").map(|k| k.to_string()))
        .collect()
}

/// Turn raw `ausearch --format raw` output into events (one per audit
/// event that matches a Horcrux key or a login/account record type).
pub fn parse_events(raw: &str, names: &BTreeMap<String, String>) -> Vec<SecurityEvent> {
    let mut groups: BTreeMap<(i64, u32, u64), Vec<Record>> = BTreeMap::new();
    for l in raw.lines() {
        if let Some(r) = parse_record(l) {
            groups
                .entry((r.secs, r.millis, r.serial))
                .or_default()
                .push(r);
        }
    }
    let mut out = Vec::new();
    for ((secs, millis, serial), recs) in groups {
        if let Some(e) = event_of(secs, millis, serial, &recs, names) {
            out.push(e);
        }
    }
    out
}

fn event_of(
    secs: i64,
    millis: u32,
    serial: u64,
    recs: &[Record],
    names: &BTreeMap<String, String>,
) -> Option<SecurityEvent> {
    let id = format!("a-{secs}{millis:03}-{serial}");
    let mut e = SecurityEvent {
        id,
        at: secs,
        source: Some(EventSource::Audit),
        ..Default::default()
    };
    if let Some(sc) = recs.iter().find(|r| r.rtype == "SYSCALL") {
        let keys = hx_keys(&sc.fields);
        let kind = keys.first()?.clone();
        let f = &sc.fields;
        let failed = f.get("success").map(|s| s == "no").unwrap_or(false);
        let cwd = recs
            .iter()
            .find(|r| r.rtype == "CWD")
            .and_then(|r| r.fields.get("cwd").cloned())
            .unwrap_or_default();
        let mut path_recs: Vec<&Record> = recs
            .iter()
            .filter(|r| r.rtype == "PATH")
            .filter(|r| {
                r.fields
                    .get("nametype")
                    .map(|n| n != "PARENT")
                    .unwrap_or(true)
            })
            .collect();
        // A replace-by-rename (useradd, sed -i, editors) logs the temporary
        // name as DELETE and the watched file as CREATE: show the file.
        path_recs.sort_by_key(|r| match r.fields.get("nametype").map(|s| s.as_str()) {
            Some("NORMAL") | None => 0,
            Some("CREATE") => 1,
            _ => 2,
        });
        let paths: Vec<String> = path_recs
            .into_iter()
            .filter_map(|r| r.fields.get("name").map(|n| unhex(n)))
            .filter(|n| n != "(null)")
            .map(|n| {
                if n.starts_with('/') || cwd.is_empty() {
                    n
                } else {
                    format!("{}/{}", cwd.trim_end_matches('/'), n)
                }
            })
            .collect();
        e.kind = kind.clone();
        e.user = user_name(f.get("auid").map(|s| s.as_str()).unwrap_or(""), names);
        e.exe = f.get("exe").cloned().unwrap_or_default();
        e.path = paths.first().cloned().unwrap_or_default();
        e.result = if failed { "failed" } else { "success" }.into();
        e.severity = Some(kind_severity(&kind, failed));
        let by = if e.user.is_empty() || e.user == "unset" {
            e.exe.clone()
        } else {
            format!("{} (user {})", e.exe, e.user)
        };
        let what = if e.path.is_empty() {
            f.get("syscall")
                .map(|s| format!("syscall {s}"))
                .unwrap_or_default()
        } else {
            e.path.clone()
        };
        let verb = match kind.as_str() {
            "sudo" => "ran",
            "modules" => "kernel module change:",
            "time" => "clock change:",
            _ => "changed",
        };
        e.summary = match kind.as_str() {
            "sudo" => format!("{} ran {}", nonempty(&e.user, "someone"), what),
            "modules" | "time" => format!("{verb} {what} by {by}"),
            _ => format!("{what} {verb} by {by}"),
        };
        if failed {
            e.summary.push_str(" (denied)");
        }
        let proctitle = recs
            .iter()
            .find(|r| r.rtype == "PROCTITLE")
            .and_then(|r| r.fields.get("proctitle").map(|p| unhex(p)))
            .unwrap_or_default();
        e.detail = format!(
            "audit serial {serial}, keys {}{}",
            keys.iter()
                .map(|k| format!("hx-{k}"))
                .collect::<Vec<_>>()
                .join(","),
            if proctitle.is_empty() {
                String::new()
            } else {
                format!(", command: {proctitle}")
            }
        );
        return Some(e);
    }
    let r = recs
        .iter()
        .find(|r| USER_TYPES.contains(&r.rtype.as_str()))?;
    let f = &r.fields;
    let res = f.get("res").cloned().unwrap_or_default();
    let failed = res == "failed" || res == "no";
    let acct = f
        .get("acct")
        .map(|a| unhex(a))
        .filter(|a| !a.is_empty() && a != "?")
        .or_else(|| f.get("id").map(|i| user_name(i, names)))
        .unwrap_or_else(|| user_name(f.get("auid").map(|s| s.as_str()).unwrap_or(""), names));
    e.user = acct.clone();
    e.exe = f.get("exe").cloned().unwrap_or_default();
    e.addr = f
        .get("addr")
        .filter(|a| a.as_str() != "?")
        .cloned()
        .unwrap_or_default();
    e.result = if failed { "failed" } else { "success" }.into();
    let from = if e.addr.is_empty() {
        String::new()
    } else {
        format!(" from {}", e.addr)
    };
    match r.rtype.as_str() {
        "USER_LOGIN" => {
            e.kind = "login".into();
            e.summary = format!(
                "{} login of {}{from} ({})",
                if failed { "Failed" } else { "Successful" },
                nonempty(&acct, "unknown account"),
                e.exe
            );
        }
        "USER_AUTH" => {
            // Successful authentications repeat what USER_LOGIN / USER_CMD
            // already say.
            if !failed {
                return None;
            }
            e.kind = "auth".into();
            e.summary = format!(
                "Failed authentication for {}{from} ({})",
                nonempty(&acct, "unknown account"),
                e.exe
            );
        }
        "USER_CMD" => {
            e.kind = "sudo".into();
            let cmd = f.get("cmd").map(|c| unhex(c)).unwrap_or_default();
            e.user = user_name(f.get("auid").map(|s| s.as_str()).unwrap_or(""), names);
            e.path = cmd.clone();
            e.summary = format!(
                "{} ran '{}' with {}{}",
                nonempty(&e.user, "someone"),
                cmd,
                e.exe.rsplit('/').next().unwrap_or("sudo"),
                if failed { " (refused)" } else { "" }
            );
        }
        t => {
            e.kind = "identity".into();
            let op = f.get("op").map(|o| unhex(o)).unwrap_or_default();
            e.summary = format!(
                "Account change {t}{}: {} by {}",
                if op.is_empty() {
                    String::new()
                } else {
                    format!(" ({op})")
                },
                nonempty(&acct, "?"),
                nonempty(&e.exe, "?")
            );
        }
    }
    e.severity = Some(kind_severity(&e.kind, failed));
    e.detail = format!("audit serial {serial}, record {}", r.rtype);
    Some(e)
}

fn nonempty<'a>(s: &'a str, d: &'a str) -> &'a str {
    if s.is_empty() {
        d
    } else {
        s
    }
}

/// Events after `watermark` (secs, millis, serial).
pub fn after_watermark(
    events: Vec<SecurityEvent>,
    watermark: (i64, u32, u64),
) -> Vec<SecurityEvent> {
    events
        .into_iter()
        .filter(|e| event_key(e).is_some_and(|k| k > watermark))
        .collect()
}

/// (secs, millis, serial) of an audit event id `a-<secs><ms>-<serial>`.
pub fn event_key(e: &SecurityEvent) -> Option<(i64, u32, u64)> {
    let rest = e.id.strip_prefix("a-")?;
    let (t, s) = rest.split_once('-')?;
    if t.len() < 4 {
        return None;
    }
    let (secs, ms) = t.split_at(t.len() - 3);
    Some((secs.parse().ok()?, ms.parse().ok()?, s.parse().ok()?))
}

// ------------------------------------------------------------ AIDE

/// `/usr/lib/x.so` -> a POSIX extended regex matching that path and
/// everything below it.
pub fn aide_regex(p: &str) -> String {
    let mut o = String::new();
    for c in p.trim_end_matches('/').chars() {
        if ".+*?()[]{}|^$\\".contains(c) {
            o.push('\\');
        }
        o.push(c);
    }
    format!("{o}(/|$)")
}

pub fn render_aide_conf(s: &IntegritySettings, db_dir: &Path) -> String {
    let db = db_dir.display();
    let mut o = String::new();
    o.push_str("# Horcrux file integrity configuration (generated by horcrux-api from\n");
    o.push_str("# Security > Settings > Integrity; changes here are overwritten).\n");
    o.push_str(&format!("database_in=file:{db}/aide.db\n"));
    o.push_str(&format!("database_out=file:{db}/aide.db.new\n"));
    // Uncompressed: AIDE may be built without zlib.
    o.push_str("gzip_dbout=no\n");
    // Options apply to the report_url lines that follow them.
    o.push_str("report_format=json\n");
    o.push_str("report_level=changed_attributes\n");
    o.push_str("report_url=stdout\n");
    o.push_str("HXRULE = p+i+n+u+g+s+m+c+sha256\n");
    for x in &s.exclude {
        o.push_str(&format!("!{}\n", aide_regex(x)));
    }
    for p in &s.paths {
        // A selection line is a prefix regex; `(/|$)` keeps /usr from also
        // selecting /usrlocal-like siblings.
        o.push_str(&format!("{} HXRULE\n", aide_regex(p)));
    }
    o
}

/// Differences in one `aide --check` JSON report.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct AideReport {
    pub added: Vec<(String, String)>,
    pub removed: Vec<(String, String)>,
    /// path, summary flags, attribute diff text
    pub changed: Vec<(String, String, String)>,
    pub total_entries: u64,
}

impl AideReport {
    pub fn differences(&self) -> u32 {
        (self.added.len() + self.removed.len() + self.changed.len()) as u32
    }
}

/// Parse AIDE's `report_format=json` output (0.18+). Some versions print a
/// plain line before the JSON; the first `{` starts it.
pub fn parse_aide_json(out: &str) -> Result<AideReport, String> {
    let start = out.find('{').ok_or("AIDE printed no JSON report")?;
    let v: Value = serde_json::from_str(&out[start..])
        .or_else(|_| {
            // Several JSON documents (one per report_url): take the first.
            let mut de = serde_json::Deserializer::from_str(&out[start..]).into_iter::<Value>();
            de.next().unwrap_or(Ok(Value::Null))
        })
        .map_err(|e| format!("AIDE report: {e}"))?;
    let map = |k: &str| -> Vec<(String, String)> {
        v[k].as_object()
            .map(|m| {
                m.iter()
                    .map(|(p, f)| (p.clone(), f.as_str().unwrap_or("").trim_end().to_string()))
                    .collect()
            })
            .unwrap_or_default()
    };
    let changed = map("changed")
        .into_iter()
        .map(|(p, f)| {
            let d = v["details"][&p]
                .as_object()
                .map(|m| {
                    m.iter()
                        .map(|(attr, ch)| {
                            format!("{attr}: {} -> {}", short(&ch["old"]), short(&ch["new"]))
                        })
                        .collect::<Vec<_>>()
                        .join("; ")
                })
                .unwrap_or_default();
            (p, f, d)
        })
        .collect();
    Ok(AideReport {
        added: map("added"),
        removed: map("removed"),
        changed,
        total_entries: v["number_of_entries"]["total"].as_u64().unwrap_or(0),
    })
}

fn short(v: &Value) -> String {
    let s = match v {
        Value::String(s) => s.clone(),
        Value::Null => "-".into(),
        o => o.to_string(),
    };
    if s.chars().count() > 24 {
        format!("{}…", s.chars().take(22).collect::<String>())
    } else {
        s
    }
}

fn path_severity(p: &str) -> Severity {
    const HIGH: &[&str] = &[
        "/boot",
        "/usr/bin",
        "/usr/sbin",
        "/bin",
        "/sbin",
        "/usr/lib",
        "/usr/lib64",
        "/lib",
        "/lib64",
        "/usr/libexec",
        "/etc/pam.d",
        "/etc/sudoers",
        "/etc/shadow",
        "/etc/passwd",
        "/etc/ssh",
    ];
    if HIGH
        .iter()
        .any(|h| p == *h || p.starts_with(&format!("{h}/")))
    {
        Severity::High
    } else if p.starts_with("/etc/") {
        Severity::Medium
    } else {
        Severity::Low
    }
}

/// Events for one check: a summary plus up to `max_files` per-file events
/// (highest severity first).
pub fn integrity_events(r: &AideReport, at: i64, max_files: usize) -> Vec<SecurityEvent> {
    let mut files: Vec<SecurityEvent> = Vec::new();
    let mk = |kind: &str, p: &str, flags: &str, detail: &str| SecurityEvent {
        id: String::new(),
        at,
        source: Some(EventSource::Integrity),
        kind: kind.into(),
        severity: Some(path_severity(p)),
        summary: format!("{p} {kind}"),
        path: p.to_string(),
        detail: if detail.is_empty() {
            flags.trim().to_string()
        } else {
            format!("{} {detail}", flags.trim())
        },
        ..Default::default()
    };
    for (p, f) in &r.added {
        files.push(mk("added", p, f, ""));
    }
    for (p, f) in &r.removed {
        files.push(mk("removed", p, f, ""));
    }
    for (p, f, d) in &r.changed {
        files.push(mk("changed", p, f, d));
    }
    files.sort_by(|a, b| b.severity.cmp(&a.severity).then(a.path.cmp(&b.path)));
    let worst = files.first().and_then(|e| e.severity);
    let n = files.len();
    files.truncate(max_files);
    let mut out = vec![SecurityEvent {
        id: String::new(),
        at,
        source: Some(EventSource::Integrity),
        kind: "summary".into(),
        severity: worst.or(Some(Severity::Negligible)),
        summary: if n == 0 {
            format!(
                "Integrity check: no differences in {} entries",
                r.total_entries
            )
        } else {
            format!(
                "Integrity check: {} added, {} removed, {} changed",
                r.added.len(),
                r.removed.len(),
                r.changed.len()
            )
        },
        detail: if n > max_files {
            format!(
                "{} per-file events recorded, {} more not listed",
                max_files,
                n - max_files
            )
        } else {
            format!("{} entries checked", r.total_entries)
        },
        ..Default::default()
    }];
    out.extend(files);
    for (i, e) in out.iter_mut().enumerate() {
        e.id = format!("i-{at}-{i}");
    }
    out
}

