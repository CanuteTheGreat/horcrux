/// `<data_dir>/security/ids-state.json`.
#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq)]
#[serde(default)]
pub struct IdsState {
    /// Newest audit event taken in (secs, millis, serial).
    pub audit_watermark: (i64, u32, u64),
    pub audit_last_collect: Option<i64>,
    pub audit_error: Option<String>,
    pub integrity_initialized_at: Option<i64>,
    pub integrity_last_check: Option<i64>,
    pub integrity_last_differences: Option<u32>,
    pub integrity_error: Option<String>,
}

pub fn state_path(dd: &Path) -> PathBuf {
    dd.join("security").join("ids-state.json")
}

pub fn load_state(dd: &Path) -> IdsState {
    std::fs::read(state_path(dd))
        .ok()
        .and_then(|b| serde_json::from_slice(&b).ok())
        .unwrap_or_default()
}

pub fn save_state(dd: &Path, s: &IdsState) -> Result<(), String> {
    let p = state_path(dd);
    if let Some(d) = p.parent() {
        std::fs::create_dir_all(d).map_err(|e| format!("{}: {e}", d.display()))?;
    }
    let tmp = p.with_extension("json.tmp");
    std::fs::write(&tmp, serde_json::to_vec_pretty(s).unwrap_or_default())
        .map_err(|e| format!("{}: {e}", tmp.display()))?;
    std::fs::rename(&tmp, &p).map_err(|e| format!("{}: {e}", p.display()))
}

pub fn aide_db_dir(s: &IntegritySettings, dd: &Path) -> PathBuf {
    if s.db_dir.trim().is_empty() {
        dd.join("security").join("aide")
    } else {
        PathBuf::from(s.db_dir.trim())
    }
}

