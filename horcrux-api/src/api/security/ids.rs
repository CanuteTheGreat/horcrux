/// JSON-lines event store, newest last on disk.
pub struct EventStore {
    path: PathBuf,
}

impl EventStore {
    pub fn new(data_dir: &Path) -> Self {
        Self {
            path: data_dir.join("security").join("events.jsonl"),
        }
    }

    pub fn append(&self, events: &[SecurityEvent], keep: usize) -> Result<(), String> {
        if events.is_empty() {
            return Ok(());
        }
        if let Some(d) = self.path.parent() {
            std::fs::create_dir_all(d).map_err(|e| format!("{}: {e}", d.display()))?;
        }
        let mut f = std::fs::OpenOptions::new()
            .create(true)
            .append(true)
            .open(&self.path)
            .map_err(|e| format!("{}: {e}", self.path.display()))?;
        for e in events {
            let mut l = serde_json::to_vec(e).unwrap_or_default();
            l.push(b'\n');
            f.write_all(&l)
                .map_err(|e| format!("{}: {e}", self.path.display()))?;
        }
        drop(f);
        self.prune(keep);
        Ok(())
    }

    /// Every event, oldest first.
    pub fn all(&self) -> Vec<SecurityEvent> {
        let Ok(f) = std::fs::File::open(&self.path) else {
            return vec![];
        };
        std::io::BufReader::new(f)
            .lines()
            .map_while(Result::ok)
            .filter_map(|l| serde_json::from_str(&l).ok())
            .collect()
    }

    /// Keep the newest `keep` (rewrites only when 10 % over, so appends stay cheap).
    pub fn prune(&self, keep: usize) {
        let all = self.all();
        if all.len() <= keep + keep / 10 {
            return;
        }
        let tmp = self.path.with_extension("jsonl.tmp");
        let mut buf = Vec::new();
        for e in &all[all.len() - keep..] {
            buf.extend(serde_json::to_vec(e).unwrap_or_default());
            buf.push(b'\n');
        }
        if std::fs::write(&tmp, buf).is_ok() {
            let _ = std::fs::rename(&tmp, &self.path);
        }
    }
}

/// `GET /api/security/events` filters.
#[derive(Debug, Clone, Default, Deserialize)]
#[serde(default)]
pub struct EventQuery {
    pub source: Option<String>,
    pub kind: Option<String>,
    /// Minimum severity.
    pub severity: Option<String>,
    pub user: Option<String>,
    /// Text search over summary, path, exe, user, address and detail.
    pub q: Option<String>,
    /// Unix seconds, inclusive.
    pub since: Option<i64>,
    pub until: Option<i64>,
    pub limit: Option<usize>,
    pub offset: Option<usize>,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct EventPage {
    pub total: usize,
    pub events: Vec<SecurityEvent>,
}

/// Newest first, filtered and paged.
pub fn query(all: Vec<SecurityEvent>, q: &EventQuery) -> EventPage {
    let nz = |o: &Option<String>| {
        o.as_deref()
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .map(str::to_string)
    };
    let source = nz(&q.source);
    let kind = nz(&q.kind);
    let min = nz(&q.severity).map(|s| Severity::parse(&s));
    let user = nz(&q.user);
    let text = nz(&q.q).map(|s| s.to_lowercase());
    let mut v: Vec<SecurityEvent> = all
        .into_iter()
        .rev()
        .filter(|e| {
            source
                .as_deref()
                .is_none_or(|s| e.source.map(|x| x.as_str()) == Some(s))
        })
        .filter(|e| kind.as_deref().is_none_or(|k| e.kind == k))
        .filter(|e| min.is_none_or(|m| e.severity.is_some_and(|s| s >= m)))
        .filter(|e| user.as_deref().is_none_or(|u| e.user == u))
        .filter(|e| q.since.is_none_or(|s| e.at >= s))
        .filter(|e| q.until.is_none_or(|u| e.at <= u))
        .filter(|e| {
            text.as_deref().is_none_or(|t| {
                [&e.summary, &e.path, &e.exe, &e.user, &e.addr, &e.detail]
                    .iter()
                    .any(|f| f.to_lowercase().contains(t))
            })
        })
        .collect();
    // Stable order within one second (integrity summary first).
    v.sort_by_key(|a| std::cmp::Reverse(a.at));
    let total = v.len();
    let off = q.offset.unwrap_or(0).min(total);
    let lim = q.limit.unwrap_or(100).clamp(1, 1000);
    EventPage {
        total,
        events: v.into_iter().skip(off).take(lim).collect(),
    }
}

